import { readFile, writeFile, rename, mkdir } from 'node:fs/promises'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { resolve } from 'node:path'
import { Script } from 'node:vm'
import { createHash } from 'node:crypto'

export const root = fileURLToPath(new URL('../', import.meta.url))
const read = async path => readFile(resolve(root, path), 'utf8')
export const digest = text => createHash('sha256').update(text).digest('hex')

// These are build-time substitutions, not a runtime selector engine. Values
// are deliberately limited to class selectors/fragments safe in JS strings.
export function expandHost(text, selectors, used = new Set()) {
  const expanded = text.replace(/@host\(([\w.-]+)\)/g, (_, name) => {
    if (!Object.hasOwn(selectors, name)) throw new Error(`Unknown host adapter: ${name}`)
    const value = selectors[name]
    if (typeof value !== 'string' || !/^(?:\[class(?:\*|~)?="[\w -]+"\]|[\w-]+)$/.test(value)) {
      throw new Error(`Unsafe host adapter: ${name}`)
    }
    used.add(name)
    return value
  })
  if (expanded.includes('@host(')) throw new Error('Malformed host adapter token')
  return expanded
}

export function assertBudgets(metrics, budgets) {
  for (const [name, maximum] of Object.entries(budgets)) {
    if (!(name in metrics) || !Number.isFinite(maximum) || maximum < 0) throw new Error(`Invalid budget: ${name}`)
    if (metrics[name] > maximum) throw new Error(`${name}: ${metrics[name]} exceeds budget ${maximum}`)
  }
}

export async function renderBuild() {
  const pkg = JSON.parse(await read('package.json'))
  if (!/^\d+\.\d+\.\d+(?:-[\w.-]+)?$/.test(pkg.version)) throw new Error('Invalid package version')
  const manifest = JSON.parse(await read('src/manifest.json'))
  const selectors = JSON.parse(await read('src/host-selectors.json'))
  const used = new Set()
  const inputs = new Set()
  const load = async path => {
    if (!/^src\/[\w./-]+\.(?:js|css)$/.test(path) || path.includes('..') || inputs.has(path)) {
      throw new Error(`Invalid or duplicate source: ${path}`)
    }
    inputs.add(path)
    const source = await read(path)
    if (/\[class(?:\*|~)?="[^"]+"\]/.test(source)) throw new Error(`Register host class selectors in host-selectors.json: ${path}`)
    return expandHost(source, selectors, used).replaceAll('@version', pkg.version)
  }
  const before = await Promise.all(manifest.beforeStyles.map(load))
  const cssParts = await Promise.all(manifest.styles.map(load))
  const after = await Promise.all(manifest.afterStyles.map(load))
  const css = cssParts.join('\n')
  if (css.includes('`') || css.includes('${') || css.includes('\\')) throw new Error('CSS must be safe for a literal template; escape support needs an explicit build change')
  const unused = Object.keys(selectors).filter(key => !used.has(key))
  if (unused.length) throw new Error(`Unused host adapters: ${unused.join(', ')}`)
  const section = (path, text) => `\n// Source: ${path}\n${text.trimEnd()}\n`
  const code = `/* GENERATED by npm run build. Edit src/, never this file.\n * Version ${pkg.version}; order is defined in src/manifest.json.\n */\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(pkg.name)},\n  factory: (require) => {\n`
    + before.map((text, i) => section(manifest.beforeStyles[i], text)).join('')
    + '\nconst CSS = `\n' + css + '`\n'
    + after.map((text, i) => section(manifest.afterStyles[i], text)).join('')
    + '\nreturn { name: STYLE_ID, inject: [], apply: start }\n  },\n})\n'
  new Script(code, { filename: 'lib/client.js' })
  const metrics = { clientBytes: Buffer.byteLength(code), cssBytes: Buffer.byteLength(css), hostAdapters: used.size }
  assertBudgets(metrics, JSON.parse(await read('scripts/budgets.json')))
  return { code, css, metrics, version: pkg.version, sha256: digest(code) }
}

async function main() {
  const result = await renderBuild()
  if (process.argv.includes('--check')) {
    if (await read('lib/client.js') !== result.code) throw new Error('lib/client.js is stale; run npm run build')
    console.log('Build is current:', JSON.stringify({ ...result.metrics, version: result.version, sha256: result.sha256 }))
  } else {
    // Parse and validate everything before replacing the installed entry point.
    await mkdir(resolve(root, 'lib'), { recursive: true })
    const temporary = resolve(root, 'lib/client.js.build-tmp')
    await writeFile(temporary, result.code)
    await rename(temporary, resolve(root, 'lib/client.js'))
    console.log('Built:', JSON.stringify({ ...result.metrics, version: result.version, sha256: result.sha256 }))
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch(error => { console.error(error.message); process.exitCode = 1 })
}
